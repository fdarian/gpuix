/// The elements whose children are a string.
const TEXT_CONTENT_TAGS: &[&str] = &["text", "tspan", "textPath"];

pub(super) fn is_tag(tag: &str) -> bool {
    TAGS.contains(&tag)
}

pub(super) fn holds_text(tag: &str) -> bool {
    TEXT_CONTENT_TAGS.contains(&tag)
}

